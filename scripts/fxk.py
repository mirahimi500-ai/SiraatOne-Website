# FXK1: regenerates the "Animation strength" block at the end of assets/css/style.css (Theme menu slider, html.fxk + --fxk).
# Run after any effect/animation change:  python scripts/fxk.py assets/css/style.css
import re,sys
V='var(--fxk)'
SKIP={'so-spin','so-shine','mb-turn-next','mb-turn-prev'}
src=open(sys.argv[1]).read()
m=src.find('/* FXK1 ')
if m<0: m=src.find('/* CALM1 ')
if m>-1: src=src[:m].rstrip()+'\n'
css=re.sub(r'/\*.*?\*/','',src,flags=re.S)
def blocks(t):
  i=0;n=len(t);out=[]
  while i<n:
    j=t.find('{',i)
    if j<0: break
    pre=t[i:j].strip();d=1;k=j+1
    while k<n and d:
      if t[k]=='{':d+=1
      elif t[k]=='}':d-=1
      k+=1
    out.append((pre,t[j+1:k-1]));i=k
  return out
def fnum(x):
  t=('%.4f'%x).rstrip('0').rstrip('.'); return '0' if t in ('-0','') else t
def kv(v,kind):
  mm=re.match(r'^(-?[\d.]+)([a-z%]*)$',v.strip())
  if not mm: return v
  x=float(mm.group(1));u=mm.group(2)
  if kind=='scale':
    if x==1: return '1'
    return 'calc(1 + %s * %s)'%(fnum(x-1),V)
  if x==0 or v.strip() in ('-50%','50%'): return v.strip()  # keep centring
  return 'calc(%s%s * %s)'%(fnum(x),u,V)
def tf(val):
  def rep(m):
    fn,args=m.group(1),m.group(2)
    parts=[a.strip() for a in args.split(',')]
    if fn.startswith('scale'): parts=[kv(a,'scale') for a in parts]
    elif fn.startswith(('translate','rotate','skew')): parts=[kv(a,'move') for a in parts]
    else: return m.group(0)
    return fn+'('+','.join(parts)+')'
  return re.sub(r'([a-zA-Z0-9]+)\(([^()]*)\)',rep,val)
def scale_decls(body):
  return re.sub(r'(?<![-\w])transform\s*:\s*([^;}]+)',lambda m:'transform:'+tf(m.group(1)),body)
KF={}
def walk(items,media=None,acc=None):
  for pre,body in items:
    if pre.startswith('@keyframes'): KF[pre.split()[1]]=body
    elif pre.startswith('@media') or pre.startswith('@supports'): walk(blocks(body),pre,acc)
    elif not pre.startswith('@'): acc.append((media,pre,body))
rules=[];walk(blocks(css),None,rules)
scaled={n for n,b in KF.items() if n not in SKIP and re.search(r'(?<![-\w])transform\s*:',b)}
def split_sel(s):
  out=[];d=0;cur=''
  for ch in s:
    if ch in '([':d+=1
    elif ch in ')]':d-=1
    if ch==',' and d==0: out.append(cur.strip());cur=''
    else: cur+=ch
  out.append(cur.strip());return [x for x in out if x]
def calm_sel(s):
  r=[]
  for x in split_sel(s):
    if x.startswith(':root'): r.append(':root.fxk'+x[5:])
    elif x.startswith('html'): r.append('html.fxk'+x[4:])
    else: r.append(':root.fxk '+x)
  return ','.join(r)
out=[]
for media,sel,body in rules:
  decl=[]
  am=re.search(r'(?<![-\w])animation\s*:\s*([^;}]+)',body); an=re.search(r'(?<![-\w])animation-name\s*:\s*([^;}]+)',body)
  if am or an:
    if an: names=[x.strip() for x in an.group(1).replace('!important','').split(',')]
    else:
      names=[]
      for part in split_sel(am.group(1).replace('!important','')):
        tok=[t for t in part.split() if t in KF or t=='none']
        names.append(tok[0] if tok else None)
    imp='!important' if '!important' in (am or an).group(1) else ''
    if 'infinite' in body and any(nm=='so-spin' for nm in names if nm):
      dm=re.search(r'([\d.]+)s',(am or an).group(1)); decl.append('animation-duration:calc(%ss / %s)'%(dm.group(1) if dm else '120',V)+imp)
    elif names and all(names) and any(nm in scaled or nm=='none' for nm in names):
      decl.append('animation-name:'+','.join(nm+'-k' if nm in scaled else nm for nm in names)+imp)
  if re.search(r':hover|:active|\.pop\b|\.mag\b|:focus-visible',sel) and re.search(r'(?<![-\w])transform\s*:',body):
    t=re.search(r'(?<![-\w])transform\s*:\s*([^;}]+)',body).group(1)
    decl.append('transform:'+tf(t))
  if decl:
    r=calm_sel(sel)+'{'+';'.join(decl)+'}'
    out.append((media,r))
kf=['@keyframes %s-k{%s}'%(n,scale_decls(KF[n])) for n in sorted(scaled)]
lines=['/* FXK1 (Nov 27, owner: "an option in settings to increase or decrease the animation"): generated by scripts/fxk.py — active on html.fxk with --fxk (Theme menu › Animation slider 0–150%, 100% = normal; 0% = html.rm). Every effect keeps its timing; its movement is multiplied by --fxk: moves/turns ×k, zooms 1+(s−1)×k (centring −50% kept); decorative spin speed ×k; Dock magnification ×k (site.js); 3D page turn only from 50%. */']
lines+=kf
from collections import OrderedDict
g=OrderedDict()
for media,r in out: g.setdefault(media,[]).append(r)
for media,rs in g.items():
  lines.append((media+'{' if media else '')+''.join(rs)+('}' if media else ''))
open(sys.argv[1],'w').write(src.rstrip()+'\n'+'\n'.join(lines)+'\n')
print('keyframes',len(kf),'rules',len(out),'skipped',sorted(SKIP))
